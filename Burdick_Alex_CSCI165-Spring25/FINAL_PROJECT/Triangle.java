import java.awt.Graphics2D;
import java.awt.Color;
import java.awt.geom.Point2D;
import java.awt.geom.Line2D;

public class Triangle extends Shape {
    
    // ============== PROTECTED INSTANCE VARIABLES ================= //
    protected double base;
    protected double height;
    

	// ====================== CONSTRUCTORS ========================= //

    /**
     * Default constructor
     */
    Triangle(){}
    
    /**
     * Constructs a Triangle with the specified base and height. (Copilot)
     * 
     * @param base   the base length of the triangle
     * @param height the height of the triangle
     */
    public Triangle(double base, double height) {
        setBase(base);
        setHeight(height);
    }

    /**
     * Constructs a Triangle with the specified color, filled status, location,
     * base, and height. (Copilot)
     * 
     * @param color   the color of the triangle
     * @param filled  true if the triangle is filled, false otherwise
     * @param point   the location of the triangle as a Point object
     * @param base    the base length of the triangle
     * @param height  the height of the triangle
     */
    public Triangle(Color color, boolean filled, Point point, double base, double height) {
        super(color, filled, point);
        setBase(base);
        setHeight(height);
    }

    /**
     * Constructs a Triangle as a copy of an existing Shape object, with the 
     * specified base and height. (Copilot)
     * 
     * @param originalObject the Shape object to copy
     * @param base           the base length of the triangle
     * @param height         the height of the triangle
     */
    public Triangle(Triangle originalObject) {
        super(originalObject);
        setBase(originalObject.base);
        setHeight(originalObject.height);
    }


	// =================== GETTERS AND SETTERS ====================== //

    public double getBase() {
        return base;
    }

    public void setBase(double base) {
        this.base = base;
    }

    public double getHeight() {
        return height;
    }

    public void setHeight(double height) {
        this.height = height;
    }


	// ====================== MATH METHODS ========================= //

    /**
     * Calculates the area of the triangle using the formula:
     * 0.5 * base * height. (Copilot)
     * 
     * @return the area of the triangle as a double
     */
    @Override
    public double area() {
        return 0.5 * base * height;
    }

    /**
     * Calculates the perimeter of the triangle, assuming that it is a right
     * triangle. (Method by Copilot)
     * 
     * @return the perimeter of the triangle as a double
     */
    @Override
    public double perimeter() {
        // Assuming the triangle is a right triangle, calculate the hypotenuse
        double hypotenuse = Math.sqrt((base * base) + (height * height));
        return base + height + hypotenuse;
    }


	// ==================== EXPECTED METHODS ======================= //

    /**
     * {@inheritDoc}
     */
    @Override
    public boolean equals(Object obj) {
        if (this == obj)        return true;  // idenetity check
        if (obj == null)        return false; // null check
        if (!super.equals(obj))               // super check
            return false;
        if (getClass() != obj.getClass())     // class check
            return false;

        Triangle other = (Triangle) obj; // down cast

        if (Double.doubleToLongBits(height) != Double.doubleToLongBits(other.height))
            return false;
        if (Double.doubleToLongBits(base) != Double.doubleToLongBits(other.base))
            return false;
        return true;
    }

    /**
     * {@inheritDoc}
     */
    @Override
    public String toString() {
        return super.toString() + "\nTriangle [height=" + height + ", base=" + base + "]";
    }

    /**
     * {@inheritDoc}
     * Generated by Copilot
     */
    @Override
    public void drawObject(Graphics2D g2d) {
        // Set the color for the triangle
        g2d.setColor(getColor());

        // Get the x and y coordinates of the triangle's location
        int x = (int) point.x;
        int y = (int) point.y;

        // Define the three points of the triangle
        int[] xPoints = {x, x + (int) base, x};
        int[] yPoints = {y, y, y - (int) height};

        // Draw the triangle
        if (isFilled()) {
            g2d.fillPolygon(xPoints, yPoints, 3);
        } else {
            g2d.drawPolygon(xPoints, yPoints, 3);
        }
    }

    /**
     * {@inheritDoc}
     */
    @Override
    public double computeDistance(Point cameraPosition) {
        // Calculate the distance from the camera to the triangle
        //double distance = Math.sqrt(Math.pow(point.x - cameraPosition.x, 2) + Math.pow(point.y - cameraPosition.y, 2));
        //return distance;
        
        // Declare variables
        int x = (int) point.x;
        int y = (int) point.y;

        // Create Points for the Triangle
        Point2D.Double bottomLeft  = new Point2D.Double(x, y);
        Point2D.Double topLeft     = new Point2D.Double(x + base, y);
        Point2D.Double bottomRight = new Point2D.Double(x, y - height);
        
        // Create Lines for the Triangle
        Line2D.Double[] triangleLines = new Line2D.Double[3];
        triangleLines[0] = new Line2D.Double(bottomLeft, topLeft);
        triangleLines[1] = new Line2D.Double(topLeft, bottomRight);
        triangleLines[2] = new Line2D.Double(bottomRight, bottomLeft);
        
        // Calculate the distance from the camera to each line
        double minDistance = Double.MAX_VALUE; // suggested by Copilot
        double distance = 0;
        for (Line2D.Double line : triangleLines) {
            distance = line.ptSegDist(cameraPosition.x, cameraPosition.y);
            if (distance < minDistance) {
                minDistance = distance;
            }
        }

        return minDistance;

    }
}
