public class SavingsAccount extends Account{
    
    // Class Variables
    public static final double interestPercentage = 0.02; // public so that other classes can check interest percentage, but can't change it
    public static final double minBalance = 0;
    public static final int maxNumWithdrawals = 2;
    public static final double withDrawalLimit = 500;
    
    // Instance variables
    public int numWithdrawals = 0;
    

    // Constructors
    
    /**
	 * Overloaded constructor
     * 
	 * @param accountNumber
	 * @param owner
	 * @param created
	 * @param balance
	 */
    public SavingsAccount(int accountNumber, Customer owner, Date created, double balance) {
        super(accountNumber, owner, created, balance); // invoke super overloaded constructor
    }

    /**
	 * Overloaded constructor that accepts all fields
     * 
	 * @param accountNumber
	 * @param manager
	 * @param owner
	 * @param created
     * @param amount
     */
    public SavingsAccount(int accountNumber, Employee manager, Customer owner, Date created, double amount) {
        super(accountNumber, manager, owner, created, amount); // invoke super overloaded constructor
    }

    /**
     * Overloaded constructor that accepts an account object to be copied
     * 
     * @param account
     */
    public SavingsAccount(Account account) {
        super(account); // invoke super copy constructor
    }

    /**
     * Copy constructor written by Copilot
     * 
     * @param toCopy SavingsAccount to be copied
     */
    public SavingsAccount(SavingsAccount toCopy) {
        super(toCopy); // invoke the super class copy constructor
    }
    
    
    // Methods

    /**
     * Subtracts from the balance, unless it would go below the minimum balance
     * Throws OverdraftException if there have already been the maximum number of withdrawals
     * Throws OverdraftException if the amount being withdrawn is over the withdrawal limit
     * Throws InvalidBalance exception if the balance would go below the minimum balance
     * 
     * @return total
     */
    @Override
    public void withdraw(double amount) throws InvalidBalanceException, OverdraftException { // generated by Copilot
        // Test the total number of withdrawals
        if (numWithdrawals >= maxNumWithdrawals)
            throw new OverdraftException(
                "There have been " + numWithdrawals + 
                " withdrawals already. The limit is " + maxNumWithdrawals + " withdrawals.");

        // Test if the amount is over the withdrawal limit
        if (amount > withDrawalLimit)
            throw new OverdraftException("The withdrawal limit is " + withDrawalLimit);

        double difference = balance - amount; // store the difference
        if (difference < minBalance) {
            throw new InvalidBalanceException(
                "Withdrawal denied: Balance cannot go below the minimum balance of " + minBalance +
                ". Balance would be " + difference + ".");
        }

        // If it passes the above logic, subract the withdrawal amount from the current balance
        balance -= amount;
        numWithdrawals ++; // increment the number of withdrawals;
    }
    
    /**
     * Adds the interest earned to the principle
     * 
     * @return total
     */
     public double addInterest() {
        // I made the balance in Account protected instead of private so it can be changed by SavingsAccount and CheckingAccount
        return balance += balance * interestPercentage;
    }

    /**
     * Overriden toSTring
     * 
     * @return String of account with interest amounts added
     */
    @Override
    public String toString() {
		return 	super.toString() + "\nInterest % = " + interestPercentage;

    }

    /**
     * Overriden equals method
     * 
     * @return true if the objects are deep equals
     */
    @Override
    public boolean equals(Object obj) {
        // There are no instance variables to check, so the super equals will do all the checking
        if (!super.equals(obj)) return false; // super check
		return true;
    }

    /**
	 * Overriden clone that invokes the copy constructor
     * 
	 * @return a copy of this
	 */
    @Override
    public SavingsAccount clone() {
        SavingsAccount cloned = new SavingsAccount(this);
        return cloned;
    }

    @Override
    public void update() {
        addInterest();
    }
}