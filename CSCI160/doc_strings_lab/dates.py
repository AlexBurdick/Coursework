'''
Function to find leap years
'''
def is_leap_year(year: int) -> bool:
    """
    If a year is divisible by 4, (or 400 if centennial), returns true
    
    >>> is_leap_year(1900)
    True
    >>> is_leap_year(2000)
    True
    >>> is_leap_year(2020)
    True
    >>> is_leap_year(2021)
    False
    """
    if year % 4 == 0 or year % 400 == 0:
        return True
    return False


def is_valid_format(date: str) -> bool:
    """
    Comparison logic written by DeepSeek (11/02/2025) using the following prompt:
    1. Must be MM/DD/YYYY. Single digit months or days should be padded with a zero
    2. There are two "/" characters
    3. Month field is 2 characters
    4. Day field is 2 characters
    5. Year field is 4 characters
    6. All three fields are integers

    >>> is_valid_format("12/25/2023")
    True
    >>> is_valid_format("01/05/2023")
    True
    >>> is_valid_format("1/5/2023")  # Not padded with zeros
    False
    >>> is_valid_format("12/25/23")  # Year not 4 digits
    False
    """
    # Check if there are exactly two "/" characters
    if date.count('/') != 2:
        return False
    
    # Split the date into parts
    parts = date.split('/')
    
    # Check if we have exactly 3 parts
    if len(parts) != 3:
        return False
    
    month, day, year = parts

    # Check field lengths
    if len(month) != 2 or len(day) != 2 or len(year) != 4:
        return False
    
    # Check if all fields are numeric
    if not (month.isdigit() and day.isdigit() and year.isdigit()):
        return False
    
    # All format checks passed
    return True


def split_date(date: str) -> list[int]:
    if is_valid_format(date):
        date_nums = date.split('/')
        return [int(date_nums[0]), int(date_nums[1]), int(date_nums[2])]


def is_valid_month(month: int) -> bool:
    if 1 <= month <= 12:
        return True
    return False


